from abc import ABC, abstractmethod
from typing import Any, Dict, List, Optional, Type, TypeVar
from pydantic import BaseModel, Field

T = TypeVar("T", bound=BaseModel)


# ==============================================================================
# Standardized Provider Exception Hierarchy
# ==============================================================================

class ProviderError(Exception):
    """Base exception for all LLM provider communication and generation failures."""
    def __init__(self, message: str, provider: str, model_id: str, raw_error: Optional[Any] = None) -> None:
        super().__init__(f"[{provider}:{model_id}] {message}")
        self.provider = provider
        self.model_id = model_id
        self.raw_error = raw_error


class ProviderAuthenticationError(ProviderError):
    """Raised when an API key is missing, invalid, or unauthorized."""
    pass


class ProviderRateLimitError(ProviderError):
    """Raised when provider rate limits (TPM/RPM) are encountered."""
    pass


class ProviderTimeoutError(ProviderError):
    """Raised when a generation request exceeds the configured network timeout."""
    pass


class ProviderBudgetExceededError(ProviderError):
    """Raised when an execution would exceed configured project, provider, or agent budgets."""
    pass


class OutputTruncationError(ProviderError):
    """
    ----------------------------------------------------------------------------
    Class: OutputTruncationError
    ----------------------------------------------------------------------------
    Purpose:
        Raised when an LLM provider halts generation because the output token
        limit (max_tokens) was reached before the structured response was fully
        emitted, causing incomplete syntax or truncated text.
    ----------------------------------------------------------------------------
    """
    pass


# ==============================================================================
# Usage & Response Data Contracts
# ==============================================================================

class ProviderUsage(BaseModel):
    """
    ----------------------------------------------------------------------------
    Class: ProviderUsage
    ----------------------------------------------------------------------------
    Purpose:
        Captures granular token metrics and estimated expenditure for every
        isolated LLM generation call across all four scholarly agents.

    Attributes:
        input_tokens (int): Count of prompt tokens submitted to the provider.
        output_tokens (int): Count of completion tokens generated by the model.
        cached_input_tokens (int): Tokens served from provider prompt cache.
        cache_write_tokens (int): Tokens written into provider cache storage.
        total_tokens (int): Grand total billable tokens.
        estimated_cost_usd (float): Computed conservative cost in US Dollars.
        actual_cost_usd (Optional[float]): Provider-reported actual cost if supplied.
        currency (str): Currency identifier (default: 'USD').
        raw_usage (Dict[str, Any]): Original unparsed provider usage payload.
    ----------------------------------------------------------------------------
    """
    input_tokens: int = Field(default=0, description="Tokens in input prompt")
    output_tokens: int = Field(default=0, description="Tokens generated by model")
    cached_input_tokens: int = Field(default=0, description="Tokens read from prompt cache")
    cache_write_tokens: int = Field(default=0, description="Tokens written to prompt cache")
    total_tokens: int = Field(default=0, description="Total billable tokens")
    estimated_cost_usd: float = Field(default=0.0, description="Estimated cost in USD")
    actual_cost_usd: Optional[float] = Field(default=None, description="Actual cost if provider supplied")
    currency: str = Field(default="USD", description="Billing currency")
    raw_usage: Dict[str, Any] = Field(default_factory=dict, description="Original provider metadata")


class ProviderResponse(BaseModel):
    """
    ----------------------------------------------------------------------------
    Class: ProviderResponse
    ----------------------------------------------------------------------------
    Purpose:
        Standardized output container wrapping raw textual completion along
        with token consumption metadata and model execution details.

    Attributes:
        content (str): The raw text or JSON response emitted by the LLM.
        usage (ProviderUsage): Token and cost accounting container.
        model_id (str): The exact provider model string employed.
        provider (str): Name of the underlying provider platform.
        finish_reason (Optional[str]): Provider finish reason (e.g. 'stop', 'length').
    ----------------------------------------------------------------------------
    """
    content: str = Field(..., description="Generated text content")
    usage: ProviderUsage = Field(default_factory=ProviderUsage, description="Token consumption metrics")
    model_id: str = Field(..., description="Provider model ID utilized")
    provider: str = Field(..., description="Provider platform identifier")
    finish_reason: Optional[str] = Field(default="stop", description="Stop condition")
    is_truncated: bool = Field(default=False, description="Whether output hit max_tokens / length limit")

    @property
    def was_truncated(self) -> bool:
        """
        ------------------------------------------------------------------------
        Method: was_truncated
        ------------------------------------------------------------------------
        Purpose:
            Returns True if the LLM output was terminated prematurely by output
            token exhaustion (e.g. stop_reason 'max_tokens' or 'length').
        ------------------------------------------------------------------------
        """
        return self.is_truncated or (self.finish_reason in ("max_tokens", "length"))


# ==============================================================================
# Abstract Provider Adapter Base Class
# ==============================================================================

class BaseLLMAdapter(ABC):
    """
    ----------------------------------------------------------------------------
    Class: BaseLLMAdapter
    ----------------------------------------------------------------------------
    Purpose:
        Abstract specification defining the mandatory interface for all LLM
        integrations (Google Gemini, OpenAI GPT, Anthropic Claude). Ensures
        that agent business logic remains completely decoupled from provider-specific
        SDKs, and guarantees pre-call token estimation, prompt caching support,
        usage extraction, and offline development mock capability.
    ----------------------------------------------------------------------------
    """

    def __init__(
        self,
        model_id: str,
        api_key: Optional[str] = None,
        temperature: float = 0.20,
        max_tokens: int = 4096,
        timeout_seconds: float = 60.0,
        offline_mode: bool = False,
    ) -> None:
        """
        ------------------------------------------------------------------------
        Method: __init__
        ------------------------------------------------------------------------
        Purpose:
            Initializes the provider adapter with model settings and credentials.

        Parameters:
            model_id (str): The specific model identifier (e.g. 'gemini-1.5-pro').
            api_key (Optional[str]): The provider API secret key.
            temperature (float): Generation temperature (default 0.20 for scholarly rigor).
            max_tokens (int): Maximum output token limit (default 4096).
            timeout_seconds (float): Request network timeout in seconds.
            offline_mode (bool): If True, returns mock/offline data without making API calls.
        ------------------------------------------------------------------------
        """
        self.model_id = model_id
        self.api_key = api_key
        self.temperature = temperature
        self.max_tokens = max_tokens
        self.timeout_seconds = timeout_seconds
        self.offline_mode = offline_mode

    @property
    @abstractmethod
    def provider_name(self) -> str:
        """Returns the unique provider name (e.g., 'google', 'openai', 'anthropic')."""
        pass

    @property
    @abstractmethod
    def supports_prompt_caching(self) -> bool:
        """Returns True if the provider and model support native prompt caching."""
        pass

    @property
    @abstractmethod
    def supports_batch_api(self) -> bool:
        """Returns True if the provider offers asynchronous batch generation."""
        pass

    @abstractmethod
    def generate(
        self,
        prompt: str,
        system_prompt: Optional[str] = None,
        cached_context: Optional[str] = None,
        **kwargs: Any,
    ) -> ProviderResponse:
        """
        ------------------------------------------------------------------------
        Method: generate
        ------------------------------------------------------------------------
        Purpose:
            Executes a completion request against the provider and returns the
            standardized text response along with token usage metrics.

        Parameters:
            prompt (str): The main prompt string.
            system_prompt (Optional[str]): Dedicated system prompt instructions.
            cached_context (Optional[str]): Static reference text suitable for caching.
            **kwargs (Any): Additional provider-specific parameters.

        Returns:
            ProviderResponse: Standardized response object with content and usage.
        ------------------------------------------------------------------------
        """
        pass

    @abstractmethod
    def estimate_tokens(self, text: str) -> int:
        """
        ------------------------------------------------------------------------
        Method: estimate_tokens
        ------------------------------------------------------------------------
        Purpose:
            Estimates the token count of a given text string offline for pre-call
            budget validation without dispatching network calls.

        Parameters:
            text (str): Input text string.

        Returns:
            int: Estimated token count.
        ------------------------------------------------------------------------
        """
        pass

    def estimate_cost(self, input_tokens: int, output_tokens: int) -> float:
        """
        ------------------------------------------------------------------------
        Method: estimate_cost
        ------------------------------------------------------------------------
        Purpose:
            Computes a baseline estimated cost in USD based on standard rates.
            May be overridden by the centralized catalog.
        ------------------------------------------------------------------------
        """
        # Conservative fallback rates ($3 / M input, $15 / M output)
        return (input_tokens * 3.0 / 1_000_000) + (output_tokens * 15.0 / 1_000_000)
